"""
Week 4 Capstone - create applicants_with_simulated_features.csv

Reads the cleaned Week 1 file (applicants_cleaned_by_maryamshaikh.csv),
adds 4 SIMULATED features (generated by code, not real applicant data),
and saves the result. Keep this script and the CSV in the same folder.

Run:  python make_simulated_features.py
"""
import numpy as np
import pandas as pd

INPUT_FILE = 'applicants_cleaned_by_maryamshaikh.csv'
OUTPUT_FILE = 'applicants_with_simulated_features.csv'

df = pd.read_csv(INPUT_FILE, dtype={'Phone': str})
print("Loaded:", df.shape)

np.random.seed(42)          # makes the simulated data reproducible
LINK_TO_OUTCOME = True      # False = purely random features (no link to Status)

n = len(df)

if LINK_TO_OUTCOME:
    # strength: 1 = Selected, 0 = Rejected, 0.5 = Under Review (unknown outcome -> neutral)
    strength = np.where(df['Status'] == 'Selected', 1.0,
                np.where(df['Status'] == 'Rejected', 0.0, 0.5))
else:
    strength = np.full(n, 0.5)

df['num_skills_listed'] = np.random.randint(1, 9, size=n)   # purely random, 1-8

has_portfolio_yes = np.random.rand(n) < (0.25 + 0.35 * strength * LINK_TO_OUTCOME)
df['has_portfolio'] = np.where(has_portfolio_yes, 'Yes', 'No')

hackathon_yes = np.random.rand(n) < (0.20 + 0.15 * strength * LINK_TO_OUTCOME)
df['prior_hackathon_participation'] = np.where(hackathon_yes, 'Yes', 'No')

score = np.random.normal(loc=4.5 + 2.5 * strength * LINK_TO_OUTCOME, scale=1.8, size=n)
df['statement_quality_score'] = np.clip(np.round(score), 1, 10).astype(int)

df.to_csv(OUTPUT_FILE, index=False)
print("Saved:", OUTPUT_FILE, "| shape:", df.shape)
print(df[['Applicant Name', 'Status', 'num_skills_listed', 'has_portfolio',
          'prior_hackathon_participation', 'statement_quality_score']].head(10))
